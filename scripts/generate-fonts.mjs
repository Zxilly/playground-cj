import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { create } from 'fontkit'
import subsetFont from 'subset-font'
import { catalogCharacters, planSubsets, unicodeRange } from './font-subsets.mjs'

const root = new URL('../', import.meta.url)
const sourceDirectory = new URL('src/app/fonts/', root)
const outputDirectory = new URL('generated/', sourceDirectory)
await mkdir(outputDirectory, { recursive: true })
const localesDirectory = new URL('src/locales/', root)
const catalogs = {}
for (const locale of (await readdir(localesDirectory, { withFileTypes: true })).filter(entry => entry.isDirectory())) {
  const { messages } = await import(pathToFileURL(fileURLToPath(new URL(`${locale.name}/messages.mjs`, localesDirectory))).href)
  catalogs[locale.name] = catalogCharacters(messages)
}

const manifestUrl = new URL('manifest.json', outputDirectory)
const previous = await readFile(manifestUrl, 'utf8').then(JSON.parse).catch(() => ({ files: {} }))
const manifest = { files: {} }
const css = ['/* Generated by pnpm fonts:generate from compiled Lingui catalogs. */']
for (const [prefix, source, family] of [
  ['harmony', 'HarmonyOS_Sans.woff2', 'HarmonyOS Sans Web'],
  ['jetbrains', 'JetBrainsMono.woff2', 'JetBrains Mono Extras'],
]) {
  const buffer = await readFile(new URL(source, sourceDirectory))
  const sourceHash = createHash('sha256').update(buffer).digest('hex')
  // fontkit includes the cmap format-4 U+FFFF sentinel; it is not a character.
  const subsets = planSubsets(create(buffer).characterSet.filter(point => point !== 0xFFFF), catalogs)
  // Later matching @font-face rules win. Register exact UI ranges after the
  // broad fallback pages to keep common copy in the small catalog subsets.
  for (const { name, points } of subsets.sort((a, b) => Number(a.name.startsWith('ui-')) - Number(b.name.startsWith('ui-')))) {
    const file = `${prefix}-${name}.woff2`
    // Bump the version when changing subsetter options or dependencies.
    const key = createHash('sha256').update(JSON.stringify([1, sourceHash, points])).digest('hex')
    const target = new URL(file, outputDirectory)
    let bytes = await readFile(target).catch(() => null)
    if (!bytes || previous.files[file]?.key !== key) {
      bytes = await subsetFont(buffer, String.fromCodePoint(...points), { targetFormat: 'woff2' })
      await writeFile(target, bytes)
    }
    manifest.files[file] = { key, bytes: bytes.length, unicodeRange: unicodeRange(points) }
    if (name !== 'latin') {
      // A fallback page has at most 512 code points. Bounding its range keeps
      // CSS small; the font cmap still decides whether a character is present.
      const range = name.startsWith('range-') ? `U+${points[0].toString(16)}-${points.at(-1).toString(16)}` : unicodeRange(points)
      css.push(`@font-face { font-family: '${family}'; src: url('./${file}') format('woff2'); font-display: swap; unicode-range: ${range}; }`)
    }
  }
  console.log(`${prefix}: ${subsets.length} subsets; Latin ${manifest.files[`${prefix}-latin.woff2`].bytes.toLocaleString()} bytes`)
}
await writeFile(new URL('fonts.css', outputDirectory), `${css.join('\n')}\n`)
await writeFile(manifestUrl, `${JSON.stringify(manifest, null, 2)}\n`)
for (const file of await readdir(outputDirectory)) {
  if (file.endsWith('.woff2') && !manifest.files[file]) await rm(new URL(file, outputDirectory))
}
